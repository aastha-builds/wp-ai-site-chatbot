<?php
/**
 * WP-CLI commands for the demo content: wp sitesage demo import|save-embeddings.
 *
 * @package SiteSage
 */

namespace SiteSage;

use SiteSage\Providers\Demo_Embedding_Provider;

defined( 'ABSPATH' ) || exit;

/**
 * Import the BrightSmile Dental demo and rebuild the saved demo embeddings.
 */
class CLI_Demo {

	/**
	 * Import the fictional BrightSmile Dental pages, FAQs and PDF, then index them.
	 *
	 * ## OPTIONS
	 *
	 * [--with-leads]
	 * : Also add fictional sample leads.
	 *
	 * [--remove-sample-content]
	 * : Trash the default "Sample Page" and "Hello world!" post.
	 *
	 * ## EXAMPLES
	 *
	 *     wp sitesage demo import --with-leads
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Options.
	 * @return void
	 */
	public function import( $args, $assoc_args ) {
		$stats = ( new Demo_Importer() )->import(
			array(
				'with_leads'            => ! empty( $assoc_args['with-leads'] ),
				'remove_sample_content' => ! empty( $assoc_args['remove-sample-content'] ),
			)
		);
		if ( is_wp_error( $stats ) ) {
			\WP_CLI::error( $stats->get_error_message() );
		}
		\WP_CLI::success(
			sprintf(
				'Imported %d pages, %d FAQs, %d PDF and %d sample leads. Index: %d chunks.',
				$stats['pages'],
				$stats['faqs'],
				$stats['pdf'],
				$stats['leads'],
				isset( $stats['chunks'] ) ? $stats['chunks'] : 0
			)
		);
	}

	/**
	 * Write the current demo index vectors to demo/demo-embeddings.json.
	 *
	 * ## OPTIONS
	 *
	 * [--file=<file>]
	 * : Output file. Default: demo/demo-embeddings.json in the plugin.
	 *
	 * @subcommand save-embeddings
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Options.
	 * @return void
	 */
	public function save_embeddings( $args, $assoc_args ) {
		$file    = isset( $assoc_args['file'] ) ? $assoc_args['file'] : SITESAGE_PLUGIN_DIR . 'demo/demo-embeddings.json';
		$chunks  = Plugin::instance()->chunk_store()->all_for_model( Demo_Embedding_Provider::MODEL_ID );
		$inputs  = array();
		$vectors = array();

		foreach ( $chunks as $chunk ) {
			$inputs[] = Indexer::embedding_input( $chunk['title'], $chunk['content'] );
		}
		$idf = Demo_Embedding_Provider::build_idf( $inputs );
		foreach ( $inputs as $input ) {
			$vectors[ sha1( $input ) ] = Demo_Embedding_Provider::to_sparse( Demo_Embedding_Provider::compute( $input, $idf ) );
		}
		ksort( $vectors );

		$json = wp_json_encode(
			array(
				'model'   => Demo_Embedding_Provider::MODEL_ID,
				'note'    => 'Saved demo vectors for the BrightSmile Dental sample content. Generated by: wp sitesage demo save-embeddings',
				'idf'     => $idf,
				'vectors' => $vectors,
			)
		);
		if ( false === file_put_contents( $file, $json . "\n" ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- CLI developer command.
			\WP_CLI::error( 'Could not write ' . $file );
		}
		\WP_CLI::success( sprintf( 'Saved %d vectors to %s. Run "wp sitesage index" to use them.', count( $vectors ), $file ) );
	}
}
