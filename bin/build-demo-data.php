<?php
/**
 * Build docs/data/answers.json for the GitHub Pages preview from the saved
 * demo answers, and copy the demo PDF next to it.
 *
 * Usage: php bin/build-demo-data.php
 *
 * @package SiteSage
 */

// phpcs:disable WordPress -- Standalone build script, not loaded by WordPress.

$root    = dirname( __DIR__ );
$content = json_decode( file_get_contents( $root . '/demo/content.json' ), true );
$saved   = json_decode( file_get_contents( $root . '/demo/sample-answers.json' ), true );

$anchors = array(
	'Home'            => '#home',
	'About'           => '#about',
	'Services'        => '#services',
	'Teeth Whitening' => '#whitening',
	'Implants'        => '#implants',
	'Pricing'         => '#pricing',
	'Insurance'       => '#insurance',
	'Contact'         => '#contact',
);

/**
 * Slug like WordPress sanitize_title() for the FAQ anchors.
 *
 * @param string $title Title.
 * @return string
 */
function sitesage_slug( $title ) {
	$slug = strtolower( str_replace( array( "'", '’' ), '', $title ) );
	return trim( preg_replace( '/[^a-z0-9]+/', '-', $slug ), '-' );
}

foreach ( $content['faqs'] as $faq ) {
	$anchors[ $faq['question'] ] = '#faq-' . sitesage_slug( $faq['question'] );
}
$anchors[ $content['pdf']['title'] ] = '../data/' . $content['pdf']['file'];

$answers = array();
foreach ( $saved['answers'] as $entry ) {
	if ( 'none' !== $entry['source'] && ! isset( $anchors[ $entry['source'] ] ) ) {
		fwrite( STDERR, 'Unknown source: ' . $entry['source'] . PHP_EOL );
		exit( 1 );
	}
	$answers[] = array(
		'question'   => $entry['question'],
		'answer'     => $entry['answer'],
		'source'     => $entry['source'],
		'source_url' => 'none' === $entry['source'] ? '' : $anchors[ $entry['source'] ],
		'keywords'   => isset( $entry['keywords'] ) ? $entry['keywords'] : array(),
	);
}

$out = array(
	'notice'   => 'Interactive preview data: the 30 test questions with their saved answers (fictional BrightSmile Dental). Generated by bin/build-demo-data.php.',
	'fallback' => "I don't know that one, let me connect you with our team",
	'answers'  => $answers,
);

@mkdir( $root . '/docs/data', 0755, true );
file_put_contents( $root . '/docs/data/answers.json', json_encode( $out, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE ) . "\n" );
copy( $root . '/demo/' . $content['pdf']['file'], $root . '/docs/data/' . $content['pdf']['file'] );

echo 'Wrote docs/data/answers.json (' . count( $answers ) . " answers)\n";
